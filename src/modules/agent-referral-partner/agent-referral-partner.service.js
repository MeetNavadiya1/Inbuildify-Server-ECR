export async function createAgentReferralPartner(currentUser, body) {
  const { Users } = db;

  const {
    address,
    user,
    account_name,
    account_bsb,
    account_number,
    abn,
    company_name,
    referred_user_id,
  } = body;

  const {
    name,
    email,
    phone,
    create_login = false,
    login_id,
    password,
    password_auto_generated = false,
    manual_password,
    next_login_password_change = false,
    email_login_credentials = false,
  } = user || {};

  const existingPartner =
    await agentReferralPartnerRepo.getAgentReferralPartnerByEmail(email);

  if (existingPartner) {
    throw { status: 409, message: "Agent referral partner with this email already exists." };
  }

  if (email) {
    const existingUser = await Users.findOne({
      attributes: ["users_id"],
      where: { email },
    });

    if (existingUser) {
      throw { status: 409, message: "Email already exists in the system." };
    }
  }

  const finalLoginId = login_id;
  let finalPassword = password_auto_generated === false ? manual_password : password;
  let passwordAutoGenerated = password_auto_generated === true;
  let createdUserId = null;

  if (name && email && phone) {
    // This company's copy of the Agent role — the global template row is not
    // listed by Role Management, so permissions granted there never reach a
    // partner pinned to it.
    const agentRole = await findRoleForCompany("Agent", currentUser.company_id);

    if (!agentRole) {
      throw { status: 500, message: "Agent role not found in the system." };
    }

    const agentRoleId = agentRole.role_id;

    if (create_login) {
      if (!finalLoginId) {
        throw { status: 400, message: "Login ID is required when creating login credentials." };
      }

      if (password_auto_generated === true || !finalPassword) {
        finalPassword = generateStrongPassword();
        passwordAutoGenerated = true;
      }

      const existingLogin = await Users.findOne({
        attributes: ["users_id"],
        where: { login_id: finalLoginId },
      });

      if (existingLogin) {
        throw { status: 409, message: "Login ID already exists. Please choose a different login ID." };
      }

      if (email_login_credentials || passwordAutoGenerated) {
        try {
          await sendPasswordEmail(email, finalLoginId, finalPassword);
        } catch (error) { }
      }

      finalPassword = encrypt(finalPassword);

      const createdUser = await Users.create({
        name,
        email,
        login_id: finalLoginId,
        password: finalPassword,
        phone,
        builder_id: currentUser.builder_id || null,
        role_id: agentRoleId,
        is_active: true,
        is_locked: false,
        is_verified: true,
        password_auto_generated: passwordAutoGenerated,
        next_login_password_change,
        email_login_credentials,
        has_login: true,
      });

      createdUserId = createdUser.users_id;
    } else {
      // Create user without login credentials
      const createdUser = await Users.create({
        name,
        email,
        phone,
        builder_id: currentUser.builder_id || null,
        role_id: agentRoleId,
        is_active: true,
        is_locked: false,
        is_verified: true,
        has_login: false,
        password: "",
        login_id: null,
      });

      createdUserId = createdUser.users_id;
    }
  }

  let addressId = null;
  if (address) {
    addressId = await addressRepo.createOrUpdateAddress(null, address);
  }

  const partnerData = {
    company_id: currentUser.company_id || null,
    builder_id: currentUser.builder_id || null,
    user_id: createdUserId,
    address_id: addressId,
    account_name,
    account_bsb,
    account_number,
    abn,
    company_name,
    referred_user_id,
    created_by: currentUser.user_id || currentUser.users_id,
  };

  try {
    const partner = await agentReferralPartnerRepo.createAgentReferralPartner(partnerData);
    return keysToCamelCase(partner);
  } catch (error) {
    throw error;
  }
}

export async function getAgentReferralPartnerById(partnerId) {
  const partner = await agentReferralPartnerRepo.getAgentReferralPartnerById(partnerId);
  if (!partner) {
    throw { status: 404, message: "Agent referral partner not found." };
  }
  return keysToCamelCase(partner);
}

export async function transformAgentReferralPartnerResponse(partner) {
  const { Users, Address } = db;
  const transformed = keysToCamelCase(partner);

  let userObject = {};
  if (partner.userId) {
    const user = await Users.findOne({
      attributes: [
        "users_id", "name", "email", "phone", "login_id", "password",
        "next_login_password_change", "email_login_credentials",
        "password_auto_generated", "is_active",
      ],
      where: {
        users_id: partner.userId,
        is_deleted: false,
      },
    });

    if (user) {
      userObject = {
        userId: user.users_id,
        name: user.name,
        email: user.email,
        phone: user.phone,
        createLogin: user.password_auto_generated || false,
        loginId: user.login_id,
        passwordOption: user.password ? "manual" : null,
        manualPassword: user.password || null,
        nextLoginPasswordChange: user.next_login_password_change || false,
        emailLoginCredentials: user.email_login_credentials || false,
        isActive: user.is_active,
      };
    }
  }

  let addressObject = {};
  if (partner.addressId) {
    const address = await Address.findOne({
      attributes: ["address_id", "address_line1", "address_line2", "city", "state_id", "country_id", "zip_code"],
      where: { address_id: partner.addressId },
    });

    if (address) {
      addressObject = {
        addressId: address.address_id,
        addressLine1: address.address_line1,
        addressLine2: address.address_line2,
        city: address.city,
        stateId: address.state_id,
        countryId: address.country_id,
        zipCode: address.zip_code,
      };
    }
  }

  delete transformed.userId;
  delete transformed.addressId;

  return {
    agentReferralPartnerId: transformed.agentReferralPartnerId,
    companyId: transformed.companyId,
    builderId: transformed.builderId,
    user: userObject,
    address: addressObject,
    companyName: transformed.companyName,
    accountName: transformed.accountName,
    accountBsb: transformed.accountBsb,
    accountNumber: transformed.accountNumber,
    abn: transformed.abn,
    referredUserId: transformed.referredUserId,
    createdBy: transformed.createdBy,
    updatedBy: transformed.updatedBy,
    createdAt: transformed.createdAt,
    updatedAt: transformed.updatedAt,
  };
}

