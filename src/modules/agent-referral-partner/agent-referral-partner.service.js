export async function updateAgentReferralPartner(currentUser, partnerId, body) {
  const { Users } = db;

  const existingPartner = await agentReferralPartnerRepo.getAgentReferralPartnerById(partnerId);

  if (!existingPartner) {
    throw { status: 404, message: "Agent referral partner not found." };
  }

  if (currentUser.company_id && existingPartner.company_id !== currentUser.company_id) {
    throw { status: 403, message: "You can only update partners from your own company." };
  }
  if (currentUser.builder_id && existingPartner.builder_id !== currentUser.builder_id) {
    throw { status: 403, message: "You can only update partners from your own builder." };
  }

  const {
    address, user, account_name, account_bsb, account_number,
    abn, company_name, referred_user_id,
  } = body;

  const {
    name, email, phone, create_login, login_id, password,
    password_auto_generated = false, manual_password,
    next_login_password_change, email_login_credentials, is_active,
  } = user || {};

  // Get existing user email if not provided
  let userEmail = email;
  if (!userEmail && existingPartner.user_id) {
    const existingUser = await Users.findOne({
      attributes: ["email"],
      where: { users_id: existingPartner.user_id },
    });
    if (existingUser) {
      userEmail = existingUser.email;
    }
  }

  if (email && existingPartner.user_id) {
    const existingEmail = await Users.findOne({
      attributes: ["users_id"],
      where: {
        email,
        users_id: { [Op.ne]: existingPartner.user_id },
      },
    });

    if (existingEmail) {
      throw { status: 409, message: "Email already exists in the system." };
    }
  }

  let addressId = existingPartner.address_id;
  if (address) {
    addressId = await addressRepo.createOrUpdateAddress(existingPartner.address_id, address);
  }

  let finalLoginId = login_id || existingPartner.login_id;
  let finalPassword = password_auto_generated === false
    ? manual_password
    : password || existingPartner.password;
  let passwordAutoGenerated = password_auto_generated === true;

  if (create_login !== undefined && create_login !== existingPartner.create_login) {
    if (create_login) {
      if (!finalLoginId) {
        throw { status: 400, message: "Login ID is required when creating login credentials." };
      }

      const existingLogin = await Users.findOne({
        attributes: ["users_id"],
        where: {
          login_id: finalLoginId,
          users_id: { [Op.ne]: existingPartner.user_id },
        },
      });

      if (existingLogin) {
        throw { status: 409, message: "Login ID already exists. Please choose a different login ID." };
      }

      if (password_auto_generated === true || !finalPassword) {
        finalPassword = generateStrongPassword();
        passwordAutoGenerated = true;
      }

      if (email_login_credentials || passwordAutoGenerated) {
        try {
          await sendPasswordEmail(userEmail, finalLoginId, finalPassword);
        } catch (error) { }
      }

      finalPassword = encrypt(finalPassword);
    } else {
      finalLoginId = null;
      finalPassword = null;
      passwordAutoGenerated = false;
    }
  } else if (create_login && password_auto_generated === false && manual_password) {
    if (finalLoginId) {
      const existingLogin = await Users.findOne({
        attributes: ["users_id"],
        where: {
          login_id: finalLoginId,
          users_id: { [Op.ne]: existingPartner.user_id },
        },
      });

      if (existingLogin) {
        throw { status: 409, message: "Login ID already exists. Please choose a different login ID." };
      }
    }

    if (email_login_credentials) {
      try {
        await sendPasswordEmail(userEmail, finalLoginId, manual_password);
      } catch (error) {
      }
    }

    finalPassword = encrypt(manual_password);
    passwordAutoGenerated = false;
  }

  if (create_login === false && existingPartner.user_id) {
    await Users.update(
      { is_verified: false, is_active: false, login_id: null },
      { where: { users_id: existingPartner.user_id } },
    );
  }

  if (existingPartner.user_id) {
    const userUpdateData = {};

    if (name !== undefined) {
      userUpdateData.name = name;
    }
    if (email !== undefined) {
      userUpdateData.email = email;
    }
    if (phone !== undefined) {
      userUpdateData.phone = phone;
    }
    if (is_active !== undefined) {
      userUpdateData.is_active = is_active;
    }

    if (create_login !== undefined) {
      if (create_login) {
        const existingUser = await Users.findOne({
          attributes: ["role_id"],
          where: { users_id: existingPartner.user_id },
        });

        if (!existingUser?.role_id) {
          const agentRole = await findRoleForCompany("Agent", currentUser.company_id);
          if (agentRole) {
            userUpdateData.role_id = agentRole.role_id;
          }
        }

        userUpdateData.login_id = finalLoginId;
        userUpdateData.password = finalPassword;
        userUpdateData.password_auto_generated = passwordAutoGenerated;
        userUpdateData.next_login_password_change = next_login_password_change;
        userUpdateData.is_verified = true;
        userUpdateData.has_login = true;
      } else {
        userUpdateData.login_id = null;
        userUpdateData.is_active = false;
        userUpdateData.is_verified = false;
        userUpdateData.has_login = false;
      }
    } else if (finalLoginId && finalPassword) {
      userUpdateData.login_id = finalLoginId;
      userUpdateData.password = finalPassword;
      userUpdateData.password_auto_generated = passwordAutoGenerated;
      userUpdateData.next_login_password_change = next_login_password_change;
    }

    if (Object.keys(userUpdateData).length > 0) {
      await Users.update(userUpdateData, {
        where: { users_id: existingPartner.user_id },
      });
    }
  }

  if (referred_user_id !== undefined && referred_user_id !== null) {
    const referredUser = await Users.findOne({
      attributes: ["users_id"],
      where: {
        users_id: referred_user_id,
        is_deleted: false,
        is_active: true,
      },
    });

    if (!referredUser) {
      throw { status: 400, message: "Referred user not found or is inactive." };
    }
  }

  const updateData = {
    address_id: addressId,
    account_name: account_name !== undefined ? account_name : existingPartner.account_name,
    account_bsb: account_bsb !== undefined ? account_bsb : existingPartner.account_bsb,
    account_number: account_number !== undefined ? account_number : existingPartner.account_number,
    abn: abn !== undefined ? abn : existingPartner.abn,
    company_name: company_name !== undefined ? company_name : existingPartner.company_name,
    referred_user_id: referred_user_id !== undefined ? referred_user_id : existingPartner.referred_user_id,
    updated_by: currentUser.user_id || currentUser.users_id,
  };

  const partner = await agentReferralPartnerRepo.updateAgentReferralPartner(partnerId, updateData);
  return keysToCamelCase(partner);
}

export async function deleteAgentReferralPartner(currentUser, partnerId) {
  const existingPartner = await agentReferralPartnerRepo.getAgentReferralPartnerById(partnerId);

  if (!existingPartner) {
    throw { status: 404, message: "Agent referral partner not found." };
  }

  if (currentUser.company_id && existingPartner.company_id !== currentUser.company_id) {
    throw { status: 403, message: "You can only delete partners from your own company." };
  }
  if (currentUser.builder_id && existingPartner.builder_id !== currentUser.builder_id) {
    throw { status: 403, message: "You can only delete partners from your own builder." };
  }

  const partner = await agentReferralPartnerRepo.deleteAgentReferralPartner(partnerId);
  return keysToCamelCase(partner);
}

